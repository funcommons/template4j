package __PACKAGE__;

import fun.commons.template4j.core.RenderEngine;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.RequestBody;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RequestParam;
import org.springframework.web.bind.annotation.RestController;

import java.util.Map;

/**
 * Minimal Spring Boot controller exposing template4j's render engine.
 *
 * <p>Two endpoints:
 * <ul>
 *   <li>GET  /api/render?template=...&data=... — query-string form, easy curl test</li>
 *   <li>POST /api/render — JSON body, production form</li>
 * </ul>
 *
 * <p>Example curl:
 * <pre>
 *   curl 'http://localhost:8080/api/render?template=%7B%22v%22%3A%22Hello%2C%20%7B%40name%7D%22%7D&data=%7B%22name%22%3A%22world%22%7D'
 *   # returns: {"rendered":{"v":"Hello, world"}}
 * </pre>
 *
 * <p>Generated by template4j skill. Edit freely.
 */
@RestController
@RequestMapping("/api")
public class TemplateController {

    private final RenderEngine engine = RenderEngine.build();

    /** GET form: ?template={"msg":"hello"}&data={"name":"world"} */
    @GetMapping("/render")
    public Map<String, Object> renderGet(
            @RequestParam(defaultValue = "{\"msg\":\"hello, {@name}\"}") String template,
            @RequestParam(defaultValue = "{\"name\":\"world\"}") String data) throws Exception {
        return doRender(template, data);
    }

    /** POST form: { "template": "...", "data": { ... } } */
    @PostMapping("/render")
    public Map<String, Object> renderPost(@RequestBody Map<String, Object> body) throws Exception {
        String template = (String) body.getOrDefault("template", "{}");
        Object data = body.getOrDefault("data", Map.of());
        return doRenderObject(template, data);
    }

    @SuppressWarnings("unchecked")
    private Map<String, Object> doRender(String template, String dataJson) throws Exception {
        // data 是 JSON 字符串,解析成 Map
        Map<String, Object> dataMap = engine.renderJson(dataJson, Map.of());
        Object rendered = engine.renderJson(template, dataMap);
        return Map.of("rendered", rendered);
    }

    private Map<String, Object> doRenderObject(String template, Object data) throws Exception {
        @SuppressWarnings("unchecked")
        Map<String, Object> dataMap = (data instanceof Map)
                ? (Map<String, Object>) data
                : Map.of();
        Object rendered = engine.renderJson(template, dataMap);
        return Map.of("rendered", rendered);
    }
}
