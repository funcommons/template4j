package fun.commons.template4j.core;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.Test;

import java.util.LinkedHashMap;
import java.util.Map;

/**
 * Covers RenderEngine.withBeans() missed branch (duplicate bean name check).
 */
public class RenderEngineWithBeansBranchTest {

    @Test
    public void testWithBeansHappyPath() throws Exception {
        Map<String, Object> beans = new LinkedHashMap<>();
        beans.put("svc1", "service1");
        beans.put("svc2", "service2");
        RenderEngine engine = RenderEngine.build().withBeans(beans);
        Assertions.assertNotNull(engine);
    }

    @Test
    public void testWithBeansEmptyMap() throws Exception {
        // Covers the for-loop's false branch (empty map, no iteration)
        RenderEngine engine = RenderEngine.build().withBeans(Map.of());
        Assertions.assertNotNull(engine);
    }

    @Test
    public void testWithBeansNullArg() throws Exception {
        Assertions.assertThrows(NullPointerException.class, () -> {
        // Covers the @NonNull null-check branch generated by Lombok
        RenderEngine.build().withBeans(null);
            });
    }

    @Test
    public void testWithBeansDuplicateKey() throws Exception {
        Assertions.assertThrows(Exception.class, () -> {
        // withBean throws if beans.containsKey(name) is true
        // This covers the missed branch in withBean where the duplicate check fires
        RenderEngine engine = RenderEngine.build();
        engine.withBean("dup", "value1");
        // Second call with same name triggers the exception
        engine.withBean("dup", "value2");
            });
    }
}
